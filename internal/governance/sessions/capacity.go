func initializeCapacity(s *state) {
	s.CapacityPolicies = map[string]HostCapacityPolicy{}
	s.CapacityObservers = map[string]HostCapacityObserver{}
	s.CapacityObservations = map[string]HostCapacityObservation{}
	s.CapacityQualifications = map[string]HostCapacityQualification{}
}

func capacityFactKey(hostSessionID, executorInstanceID string) string {
	return identity("dacli-host-capacity-instance/v1", "", struct {
		HostSessionID      string
		ExecutorInstanceID string
	}{HostSessionID: hostSessionID, ExecutorInstanceID: executorInstanceID})
}

func validateHostCapacityState(s *state) error {
	for id, observer := range s.CapacityObservers {
		session, ok := s.Sessions[id]
		if !ok || observer.SchemaVersion != 1 || observer.ObserverSessionID != id || !validID(id) || !validID(observer.HostSessionID) || !validID(observer.ExecutorInstanceID) || !validID(observer.HostID) || !validID(observer.Runtime) || !validID(observer.Build) || len(observer.CapabilityDigest) != 64 || strings.Trim(observer.CapabilityDigest, "0123456789abcdef") != "" || observer.EnrolledAt.IsZero() || !observer.ExpiresAt.After(observer.EnrolledAt) || observer.ExpiresAt.After(session.ExpiresAt) || !validCapacityObserverScope(s, id, observer) {
			return ErrStorage
		}
		if _, ok := s.Sessions[observer.HostSessionID]; !ok {
			return ErrStorage
		}
	}
	for key, policy := range s.CapacityPolicies {
		if key != capacityFactKey(policy.HostSessionID, policy.ExecutorInstanceID) || policy.SchemaVersion != 1 || policy.WorkspaceID != s.Binding.Workspace || policy.InstallationID != s.Binding.Installation || !validID(policy.HostID) || !validID(policy.Runtime) || !validID(policy.Build) || !validID(policy.ExecutorInstanceID) || len(policy.CapabilityDigest) != 64 || strings.Trim(policy.CapabilityDigest, "0123456789abcdef") != "" || !capacityStateValid(policy.State, policy.RequestedSlots) || policy.Freshness <= 0 || policy.Freshness > 24*time.Hour || !validID(policy.Revision) || policy.ConfiguredAt.IsZero() {
			return ErrStorage
		}
		bound := false
		for _, observer := range s.CapacityObservers {
			if observer.HostSessionID == policy.HostSessionID && observer.ExecutorInstanceID == policy.ExecutorInstanceID && observer.HostID == policy.HostID && observer.Runtime == policy.Runtime && observer.Build == policy.Build && observer.CapabilityDigest == policy.CapabilityDigest {
				bound = true
				break
			}
		}
		if !bound {
			return ErrStorage
		}
	}
	sequences := map[string]map[uint64]time.Time{}
	for key, observation := range s.CapacityObservations {
		r := observation.HostCapacityObservationRequest
		observer, ok := s.CapacityObservers[observation.ObserverSessionID]
		wantDigest := identity("dacli-host-capacity-observation/v1", observation.ObserverSessionID, r)
		if observation.Census != nil {
			if s.Version < 22 || r.SchemaVersion != 2 || !validHostCapacityCensus(*observation.Census) {
				return ErrStorage
			}
			for _, binding := range observation.Census.IncludedLocalExecutions {
				dispatch, exists := s.Dispatches[binding.DispatchID]
				intent, intentExists := s.DispatchIntents[binding.DispatchID]
				if !exists || !intentExists || dispatch.HostSlot == nil || dispatch.HostSlot.AuthorityDomainID != observation.Census.AuthorityDomainID || dispatch.HostSlot.HostSessionID != r.HostSessionID || dispatch.HostSlot.ExecutorInstanceID != r.ExecutorInstanceID || dispatch.HostSlot.HostID != r.HostID || dispatch.HostSlot.CapabilityDigest != r.CapabilityDigest || dispatch.Reservation.Fence != binding.ReservationFence || intent.ID != binding.IntentID || intent.OperationKey != binding.OriginalOperationKey || intent.HostAgentID != binding.HostAgentID || intent.Reservation.Reservation.Fence != binding.ReservationFence || (intent.State != "host_correlated" && intent.State != "acknowledged") {
					return ErrStorage
				}
			}
			if r.OccupiedSlots > math.MaxInt-r.AvailableSlots || r.OccupiedSlots+r.AvailableSlots != r.DeclaredSlots || len(observation.Census.IncludedLocalExecutions) > r.OccupiedSlots {
				return ErrStorage
			}
			wantDigest = identity("dacli-host-capacity-observation/v2", observation.ObserverSessionID, struct {
				Request HostCapacityObservationRequest
				Census  HostCapacityCensus
			}{r, *observation.Census})
		} else if r.SchemaVersion != 1 {
			return ErrStorage
		}
		base := r
		if observation.Census != nil {
			base.SchemaVersion = 1
		}
		if key != r.OperationKey || !validateCapacityObservation(base) || observation.InputDigest != wantDigest || observation.ReceivedAt.IsZero() || r.ObservedAt.After(observation.ReceivedAt) || !ok || observer.HostSessionID != r.HostSessionID || observer.ExecutorInstanceID != r.ExecutorInstanceID || observer.HostID != r.HostID || observer.Runtime != r.Runtime || observer.Build != r.Build || observer.CapabilityDigest != r.CapabilityDigest {
			return ErrStorage
		}
		sequenceKey := capacityFactKey(r.HostSessionID, r.ExecutorInstanceID)
		seen := sequences[sequenceKey]
		if seen == nil {
			seen = map[uint64]time.Time{}
			sequences[sequenceKey] = seen
		}
		if _, duplicate := seen[r.Sequence]; duplicate {
			return ErrStorage
		}
		for sequence, received := range seen {
			if (observation.ReceivedAt.After(received) && r.Sequence <= sequence) || (received.After(observation.ReceivedAt) && sequence <= r.Sequence) {
				return ErrStorage
			}
		}
		seen[r.Sequence] = observation.ReceivedAt
	}
	for key, qualification := range s.CapacityQualifications {
		host, hostOK := s.Sessions[qualification.HostSessionID]
		if !hostOK || key != capacityFactKey(qualification.HostSessionID, qualification.ExecutorInstanceID) || qualification.SchemaVersion != 1 || !validID(qualification.HostSessionID) || !validID(qualification.ExecutorInstanceID) || !validID(qualification.HostID) || !validID(qualification.Runtime) || !validID(qualification.Build) || len(qualification.CapabilityDigest) != 64 || strings.Trim(qualification.CapabilityDigest, "0123456789abcdef") != "" || !validID(qualification.QualificationID) || !capacityStateValid(qualification.State, qualification.QualifiedSlots) || qualification.QualifiedAt.IsZero() || (qualification.State == CapacityKnown && (len(qualification.EvidenceDigest) != 64 || strings.Trim(qualification.EvidenceDigest, "0123456789abcdef") != "")) || (qualification.State != CapacityKnown && qualification.EvidenceDigest != "") || (!qualification.ExpiresAt.IsZero() && (!qualification.ExpiresAt.After(qualification.QualifiedAt) || qualification.ExpiresAt.After(host.ExpiresAt))) {
			return ErrStorage
		}
		bound := false
		for _, observer := range s.CapacityObservers {
			if observer.HostSessionID == qualification.HostSessionID && observer.ExecutorInstanceID == qualification.ExecutorInstanceID && observer.HostID == qualification.HostID && observer.Runtime == qualification.Runtime && observer.Build == qualification.Build && observer.CapabilityDigest == qualification.CapabilityDigest {
				bound = true
				break
			}
		}
		if !bound {
			return ErrStorage
		}
	}
	return nil
}

// UpgradeHostSlots is the explicit owner-authenticated schema-21 to 22
// migration. Slot policy/claim fields remain absent on every old record.
func (a *Authority) UpgradeHostSlots(owner string) error {
	old := *a
	old.version = 21
	old.strictRead = true
	err := old.transaction(false, true, func(s *state) error {
		if s.Version != 21 || len(owner) != 64 || hash(owner) != s.OwnerHash {
			return ErrDenied
		}
		// Validate the entire source before changing its version. The existing
		// transaction commits atomically and preserves all schema-21 records.
		if validateHostCapacityState(s) != nil {
			return ErrStorage
		}
		s.Version = 22
		return nil
	})
	if err == nil {
		a.version = 22
	}
	return err
}

// OpenHostSlots opens only schema 22 and never upgrades an authority.
func OpenHostSlots(path string, binding Binding, admission ...LeaseAdmission) (*Authority, error) {
	a, err := Open(path, binding, admission...)
	if err != nil {
		return nil, err
	}
	a.version, a.strictRead = 22, true
	if err := a.transaction(false, false, func(s *state) error {
		if s.Version != 22 {
			return ErrStorage
		}
		return nil
	}); err != nil {
		return nil, err
	}
	return a, nil
}

// OpenCapacityCurrent selects only the exact capacity schemas supported by
// current adapters; the legacy exact-21 opener remains unchanged.
func OpenCapacityCurrent(path string, binding Binding, admission ...LeaseAdmission) (*Authority, error) {
	a, err := OpenCurrent(path, binding, admission...)
	if err != nil {
		return nil, err
	}
	if a.version != 21 && a.version != 22 {
		return nil, ErrStorage
	}
	return a, nil
}

// UpgradeHostCapacity is the explicit owner-authenticated schema-20 to 21
// migration. It adds only empty capacity collections and preserves all prior
// semantic records verbatim.
func (a *Authority) UpgradeHostCapacity(owner string) error {
	old := *a
	old.version = 20
	old.strictRead = true
	err := old.transaction(false, true, func(s *state) error {
		if s.Version != 20 || len(owner) != 64 || hash(owner) != s.OwnerHash {
			return ErrDenied
		}
		initializeCapacity(s)
		s.Version = 21
		return nil
	})
	if err == nil {
		a.version = 21
	}
	return err
}

// OpenHostCapacity opens only schema 21; it never upgrades an authority.
func OpenHostCapacity(path string, binding Binding, admission ...LeaseAdmission) (*Authority, error) {
	a, err := Open(path, binding, admission...)
	if err != nil {
		return nil, err
	}
	a.version = 21
	if err := a.transaction(false, false, func(s *state) error {
		if s.Version != 21 {
			return ErrStorage
		}
		return nil
	}); err != nil {
		return nil, err
	}
	return a, nil
}

func capacityStateValid(state string, value int) bool {
	switch state {
	case CapacityKnown:
		return value >= 0
	case CapacityUnknown, CapacityUnsupported:
		return value == 0
	default:
		return false
	}
}

func validCapacityObserverScope(s *state, sessionID string, observer HostCapacityObserver) bool {
	r, ok := s.Sessions[sessionID]
	if !ok || r.ID != sessionID || r.Parent != "" || r.Scope.Actions == nil || !reflect.DeepEqual(r.Scope.Actions, []string{"capacity.observe"}) {
		return false
	}
	want := []string{"host:" + observer.HostID, "instance:" + observer.ExecutorInstanceID, "session:" + observer.HostSessionID, "workspace:" + s.Binding.Workspace}
	return reflect.DeepEqual(r.Scope.Resources, want)
}

// EnrollHostCapacityObserver creates a distinct owner-enrolled observer
// credential with only the exact host/session observation scope.
func (a *Authority) EnrollHostCapacityObserver(owner string, in HostCapacityObserver) (HostCapacityObserver, string, error) {
	var out HostCapacityObserver
	if in.SchemaVersion != 1 {
		return out, "", ErrDenied
	}
	token, err := mint()
	if err != nil {
		return out, "", err
	}
	id, err := mint()
	if err != nil {
		return out, "", err
	}
	in.SchemaVersion = 1
	in.ObserverSessionID = id
	in.EnrolledAt = time.Now().UTC()
	in.ExpiresAt = in.ExpiresAt.Round(0).UTC()
	err = a.transaction(false, true, func(s *state) error {
		host, ok := s.Sessions[in.HostSessionID]
		if !supportedCapacitySchema(s.Version) || len(owner) != 64 || hash(owner) != s.OwnerHash || !ok || authenticateRecord(s, in.HostSessionID, time.Now()) != nil || in.HostSessionID == "" || !validID(in.ExecutorInstanceID) || in.HostID == "" || !validID(in.HostID) || !validID(in.Runtime) || !validID(in.Build) || len(in.CapabilityDigest) != 64 || strings.Trim(in.CapabilityDigest, "0123456789abcdef") != "" || !in.ExpiresAt.After(time.Now()) || in.ExpiresAt.After(host.ExpiresAt) {
			return ErrDenied
		}
		observer := HostCapacityObserver{SchemaVersion: 1, ObserverSessionID: id, HostSessionID: in.HostSessionID, ExecutorInstanceID: in.ExecutorInstanceID, HostID: in.HostID, Runtime: in.Runtime, Build: in.Build, CapabilityDigest: in.CapabilityDigest, ExpiresAt: in.ExpiresAt, EnrolledAt: in.EnrolledAt}
		scope := Scope{Actions: []string{"capacity.observe"}, Resources: []string{"host:" + in.HostID, "instance:" + in.ExecutorInstanceID, "session:" + in.HostSessionID, "workspace:" + s.Binding.Workspace}}
		s.Sessions[id] = record{Session: Session{ID: id, Scope: scope, ExpiresAt: in.ExpiresAt}, Hash: hash(token)}
		s.CapacityObservers[id] = observer
		out = observer
		return nil
	})
	if err != nil {
		return HostCapacityObserver{}, "", err
	}
	return out, token, nil
}

func authenticateRecord(s *state, id string, now time.Time) error {
	seen := map[string]bool{}
	for id != "" {
		if seen[id] {
			return ErrDenied
		}
		seen[id] = true
		r, ok := s.Sessions[id]
		if !ok || r.Revoked || !now.Before(r.ExpiresAt) {
			return ErrDenied
		}
		id = r.Parent
	}
	return nil
}

func (a *Authority) ConfigureHostCapacityPolicy(owner string, p HostCapacityPolicy) (HostCapacityPolicy, error) {
	var out HostCapacityPolicy
	if p.SchemaVersion != 1 {
		return out, ErrDenied
	}
	p.SchemaVersion = 1
	p.ConfiguredAt = time.Now().UTC()
	err := a.transaction(false, true, func(s *state) error {
		if !supportedCapacitySchema(s.Version) || len(owner) != 64 || hash(owner) != s.OwnerHash || p.WorkspaceID != s.Binding.Workspace || p.InstallationID != s.Binding.Installation || !validID(p.HostID) || !validID(p.Runtime) || !validID(p.Build) || !validID(p.HostSessionID) || !validID(p.ExecutorInstanceID) || len(p.CapabilityDigest) != 64 || strings.Trim(p.CapabilityDigest, "0123456789abcdef") != "" || !capacityStateValid(p.State, p.RequestedSlots) || p.Freshness <= 0 || p.Freshness > 24*time.Hour || !validID(p.Revision) {
			return ErrDenied
		}
		if _, ok := s.Sessions[p.HostSessionID]; !ok || authenticateRecord(s, p.HostSessionID, time.Now()) != nil {
			return ErrDenied
		}
		bound := false
		for _, observer := range s.CapacityObservers {
			if observer.HostSessionID == p.HostSessionID && observer.ExecutorInstanceID == p.ExecutorInstanceID && observer.HostID == p.HostID && observer.Runtime == p.Runtime && observer.Build == p.Build && observer.CapabilityDigest == p.CapabilityDigest {
				bound = true
				break
			}
		}
		if !bound {
			return ErrDenied
		}
		s.CapacityPolicies[capacityFactKey(p.HostSessionID, p.ExecutorInstanceID)] = p
		out = p
		return nil
	})
	return out, err
}

func validateCapacityObservation(r HostCapacityObservationRequest) bool {
	if r.SchemaVersion != 1 || !validID(r.OperationKey) || !validID(r.HostID) || !validID(r.Runtime) || !validID(r.Build) || !validID(r.HostSessionID) || !validID(r.ExecutorInstanceID) || len(r.CapabilityDigest) != 64 || strings.Trim(r.CapabilityDigest, "0123456789abcdef") != "" || r.Sequence == 0 || r.ObservedAt.IsZero() || !capacityStateValid(r.DeclarationState, r.DeclaredSlots) || !capacityStateValid(r.ObservedState, r.OccupiedSlots) {
		return false
	}
	if r.ObservedState == CapacityKnown {
		if r.AvailableSlots < 0 || r.OccupiedSlots > math.MaxInt-r.AvailableSlots {
			return false
		}
	} else if r.AvailableSlots != 0 {
		return false
	}
	return true
}

func (a *Authority) RecordHostCapacityObservation(token, observerSessionID string, r HostCapacityObservationRequest) (HostCapacityObservation, bool, error) {
	var out HostCapacityObservation
	digest := identity("dacli-host-capacity-observation/v1", observerSessionID, r)
	duplicate := false
	err := a.transaction(false, true, func(s *state) error {
		if !supportedCapacitySchema(s.Version) || !validateCapacityObservation(r) {
			return ErrDenied
		}
		observer, ok := s.CapacityObservers[observerSessionID]
		if !ok || observer.ObserverSessionID != observerSessionID || observer.HostID != r.HostID || observer.Runtime != r.Runtime || observer.Build != r.Build || observer.HostSessionID != r.HostSessionID || observer.ExecutorInstanceID != r.ExecutorInstanceID || observer.CapabilityDigest != r.CapabilityDigest || !time.Now().Before(observer.ExpiresAt) || !validObserverCredentialScope(s, token, observerSessionID, observer) {
			return ErrDenied
		}
		if err := authenticateRecord(s, observer.HostSessionID, time.Now()); err != nil {
			return ErrDenied
		}
		if !r.ObservedAt.Before(time.Now()) {
			return ErrDenied
		}
		if old, exists := s.CapacityObservations[r.OperationKey]; exists {
			if old.InputDigest != digest {
				return ErrDenied
			}
			out, duplicate = old, true
			return nil
		}
		for _, old := range s.CapacityObservations {
			if old.HostSessionID == r.HostSessionID && old.ExecutorInstanceID == r.ExecutorInstanceID && r.Sequence <= old.Sequence {
				return ErrDenied
			}
		}
		out = HostCapacityObservation{HostCapacityObservationRequest: r, ObserverSessionID: observerSessionID, InputDigest: digest, ReceivedAt: time.Now().UTC()}
		s.CapacityObservations[r.OperationKey] = out
		return nil
	})
	return out, duplicate, err
}

func validObserverCredentialScope(s *state, token, id string, observer HostCapacityObserver) bool {
	r, err := authenticate(s, token, id, time.Now())
	return err == nil && validCapacityObserverScope(s, id, observer) && subset([]string{"capacity.observe"}, r.Scope.Actions)
}

// QualifyHostCapacity records a separately owner-authenticated qualification;
// observer-supplied facts cannot assert qualification.
func (a *Authority) QualifyHostCapacity(owner string, q HostCapacityQualification) (HostCapacityQualification, error) {
	var out HostCapacityQualification
	if q.SchemaVersion != 1 {
		return out, ErrDenied
	}
	q.SchemaVersion = 1
	q.QualifiedAt = time.Now().UTC()
	err := a.transaction(false, true, func(s *state) error {
		if !supportedCapacitySchema(s.Version) || len(owner) != 64 || hash(owner) != s.OwnerHash || !validID(q.HostSessionID) || !validID(q.ExecutorInstanceID) || !validID(q.HostID) || !validID(q.Runtime) || !validID(q.Build) || len(q.CapabilityDigest) != 64 || strings.Trim(q.CapabilityDigest, "0123456789abcdef") != "" || !validID(q.QualificationID) || !capacityStateValid(q.State, q.QualifiedSlots) {
			return ErrDenied
		}
		if q.State == CapacityKnown && (len(q.EvidenceDigest) != 64 || strings.Trim(q.EvidenceDigest, "0123456789abcdef") != "") {
			return ErrDenied
		}
		if q.State != CapacityKnown && q.EvidenceDigest != "" {
			return ErrDenied
		}
		if !q.ExpiresAt.IsZero() {
			q.ExpiresAt = q.ExpiresAt.Round(0).UTC()
			if !q.ExpiresAt.After(q.QualifiedAt) {
				return ErrDenied
			}
		}
		host, ok := s.Sessions[q.HostSessionID]
		if !ok || authenticateRecord(s, q.HostSessionID, time.Now()) != nil || (!q.ExpiresAt.IsZero() && q.ExpiresAt.After(host.ExpiresAt)) {
			return ErrDenied
		}
		bound := false
		for _, observer := range s.CapacityObservers {
			if observer.HostSessionID == q.HostSessionID && observer.ExecutorInstanceID == q.ExecutorInstanceID && observer.HostID == q.HostID && observer.Runtime == q.Runtime && observer.Build == q.Build && observer.CapabilityDigest == q.CapabilityDigest {
				bound = true
				break
			}
		}
		if !bound {
			return ErrDenied
		}
		s.CapacityQualifications[capacityFactKey(q.HostSessionID, q.ExecutorInstanceID)] = q
		out = q
		return nil
	})
	return out, err
}

func (a *Authority) ReadHostCapacity(token, observerSessionID, hostSessionID string) (HostCapacityView, error) {
	var out HostCapacityView
	err := a.transaction(false, false, func(s *state) error {
		observer, ok := s.CapacityObservers[observerSessionID]
		if !supportedCapacitySchema(s.Version) || !ok || observer.HostSessionID != hostSessionID || !validObserverCredentialScope(s, token, observerSessionID, observer) || authenticateRecord(s, hostSessionID, time.Now()) != nil {
			return ErrDenied
		}
		factKey := capacityFactKey(hostSessionID, observer.ExecutorInstanceID)
		policy, policyOK := s.CapacityPolicies[factKey]
		qualification, qualificationOK := s.CapacityQualifications[factKey]
		var latest HostCapacityObservation
		for _, fact := range s.CapacityObservations {
			if fact.HostSessionID == hostSessionID && fact.ExecutorInstanceID == observer.ExecutorInstanceID && fact.Sequence > latest.Sequence {
				latest = fact
			}
		}
		out = HostCapacityView{SchemaVersion: 1, Policy: HostCapacityPolicy{SchemaVersion: 1, State: CapacityUnknown}, DeclarationState: CapacityUnknown, ObservationState: CapacityUnknown, QualificationState: CapacityUnknown, ConsistencyState: CapacityUnknown, ExecutorInstanceID: observer.ExecutorInstanceID}
		if policyOK {
			out.Policy = policy
			if policy.WorkspaceID != s.Binding.Workspace || policy.InstallationID != s.Binding.Installation || policy.ExecutorInstanceID != observer.ExecutorInstanceID || policy.HostID != observer.HostID || policy.Runtime != observer.Runtime || policy.Build != observer.Build || policy.CapabilityDigest != observer.CapabilityDigest {
				out.Policy.State = CapacityContradictory
			}
		}
		if qualificationOK {
			out.QualificationState, out.QualifiedSlots = qualification.State, qualification.QualifiedSlots
			out.QualificationExpiresAt = qualification.ExpiresAt
			if qualification.ExecutorInstanceID != observer.ExecutorInstanceID || qualification.HostID != observer.HostID || qualification.Runtime != observer.Runtime || qualification.Build != observer.Build || qualification.CapabilityDigest != observer.CapabilityDigest {
				out.QualificationState = CapacityContradictory
			}
			if !qualification.ExpiresAt.IsZero() && !time.Now().Before(qualification.ExpiresAt) {
				out.QualificationState = CapacityStale
			}
		}
		if latest.OperationKey != "" {
			out.Sequence, out.ObservedAt, out.ReceivedAt = latest.Sequence, latest.ObservedAt, latest.ReceivedAt
			out.DeclarationState, out.DeclaredSlots = latest.DeclarationState, latest.DeclaredSlots
			out.ObservationState, out.OccupiedSlots, out.AvailableSlots = latest.ObservedState, latest.OccupiedSlots, latest.AvailableSlots
			recordingObserver, enrolled := s.CapacityObservers[latest.ObserverSessionID]
			if !enrolled || recordingObserver.HostID != observer.HostID || recordingObserver.Runtime != observer.Runtime || recordingObserver.Build != observer.Build || recordingObserver.HostSessionID != observer.HostSessionID || recordingObserver.ExecutorInstanceID != observer.ExecutorInstanceID || recordingObserver.CapabilityDigest != observer.CapabilityDigest || !time.Now().Before(recordingObserver.ExpiresAt) || authenticateRecord(s, latest.ObserverSessionID, time.Now()) != nil {
				out.ObservationState = CapacityStale
			}
			if out.DeclarationState == CapacityKnown && out.ObservationState == CapacityKnown {
				out.ConsistencyState = CapacityConsistent
				if out.OccupiedSlots+out.AvailableSlots != out.DeclaredSlots {
					out.ConsistencyState = CapacityContradictory
				}
			}
			if policyOK && (time.Since(latest.ReceivedAt) > policy.Freshness || time.Since(latest.ObservedAt) > policy.Freshness) {
				out.DeclarationState, out.ObservationState = CapacityStale, CapacityStale
			}
		}
		out.Eligible = policyOK && (s.Version < 22 || latest.Census != nil) && out.Policy.State == CapacityKnown && policy.RequestedSlots > 0 && out.DeclarationState == CapacityKnown && out.ObservationState == CapacityKnown && out.ConsistencyState == CapacityConsistent && out.QualificationState == CapacityKnown && out.AvailableSlots >= policy.RequestedSlots && out.QualifiedSlots >= policy.RequestedSlots
		return nil
	})
	return out, err
}
